/// Define a CANopen object dictionary using an inline DSL.
///
/// # Example
/// ```ignore
/// object_dictionary! {
///     pub struct MyOd {
///         [0x1000] device_type: u32 = 0x0000_0191, ro;
///         [0x1001] error_register: u8 = 0x00, ro;
///         [0x1018] identity: record {
///             [1] vendor_id: u32 = 0x0000_1234, ro;
///             [2] product_code: u32 = 0x0001, ro;
///             [3] revision: u32 = 0x0001_0000, ro;
///             [4] serial: u32 = 0x0000_0001, ro;
///         };
///         [0x6000] inputs: record {
///             [1] input1: u8 = 0, ro, pdo;
///             [2] input2: u8 = 0, ro, pdo;
///         };
///         [0x6200] outputs: record {
///             [1] output1: u8 = 0, rw, pdo;
///         };
///     }
/// }
/// ```
#[proc_macro]
pub fn object_dictionary(input: TokenStream) -> TokenStream {
    let od_def = syn::parse_macro_input!(input as dsl::OdDefinition);
    codegen::generate(od_def).into()
}

/// Define a CANopen object dictionary from an EDS file.
///
/// # Example
/// ```ignore
/// object_dictionary_from_eds! {
///     pub struct MotorControllerOd = "motor_controller.eds";
/// }
/// ```
#[proc_macro]
pub fn object_dictionary_from_eds(input: TokenStream) -> TokenStream {
    let eds_def = syn::parse_macro_input!(input as eds_parser::EdsDefinition);
    let track = eds_parser::track_source(&eds_def);
    let generated = match eds_parser::parse_eds_to_od(eds_def).and_then(|od| {
        od.validate()?;
        Ok(od)
    }) {
        Ok(od_def) => codegen::generate(od_def),
        Err(e) => e.to_compile_error(),
    };
    quote::quote! { #track #generated }.into()
}

/// Generate a typed async SDO client from an EDS file.
///
/// Creates a struct with typed, address-qualified `read_*` and `write_*`
/// async methods for each OD entry, using `SdoDriver` under the hood. Fixed
/// subindices use names such as `read_i6041_s00_statusword`; array methods
/// include the index and accept the subindex as an argument.
///
/// # Example
/// ```ignore
/// sdo_client_from_eds! {
///     pub struct MotorClient = "motor_controller.eds";
/// }
///
/// let client = MotorClient::new(node_id);
/// let status: u16 = client.read_i6041_s00_statusword(&mut can).await?;
/// client.write_i6040_s00_controlword(0x0F, &mut can).await?;
/// ```
#[proc_macro]
pub fn sdo_client_from_eds(input: TokenStream) -> TokenStream {
    let eds_def = syn::parse_macro_input!(input as eds_parser::EdsDefinition);
    let track = eds_parser::track_source(&eds_def);
    let generated = sdo_client_codegen::generate(eds_def);
    quote::quote! { #track #generated }.into()
}

/// Generate a typed remote-device PDO codec from an EDS file.
///
/// The generated client resolves the EDS COB-IDs for one node, decodes the
/// device's statically mapped TPDOs into typed payload structs, and encodes its
/// statically mapped RPDO payloads into CAN frames. Disabled-but-mapped PDOs
/// retain their direct typed methods for use after configuration, but are not
/// claimed by generic `decode()` dispatch. Unmapped PDO records are omitted.
/// It does not own a transport or retain PDO state.
///
/// ```ignore
/// pdo_client_from_eds! {
///     pub struct MotorPdo = "motor_controller.eds";
/// }
/// let pdo = MotorPdo::new(node_id);
/// let status = pdo.decode_tpdo1(&frame)?;
/// let frame = pdo.rpdo1(MotorPdoRpdo1 { controlword: 0x0f });
/// ```
#[proc_macro]
pub fn pdo_client_from_eds(input: TokenStream) -> TokenStream {
    let eds_def = syn::parse_macro_input!(input as eds_parser::EdsDefinition);
    let track = eds_parser::track_source(&eds_def);
    let generated = pdo_client_codegen::generate(eds_def);
    quote::quote! { #track #generated }.into()
}

/// Generate the high-level remote device API from an EDS file.
///
/// This is the normal master-side API: one generated type combines stable,
/// address-qualified typed SDO methods with the typed PDO codec generated by
/// [`pdo_client_from_eds`]. Raw SDO upload/download methods remain available
/// as an escape hatch.
///
/// ```ignore
/// device_from_eds! {
///     pub struct Motor = "motor_controller.eds";
/// }
/// let motor = Motor::new(node_id);
/// let status = motor.decode_tpdo1(&frame)?;
/// let frame = motor.rpdo1(MotorRpdo1 { controlword: 0x0f });
/// motor.write_i6040_s00_controlword(0x0f, &mut can).await?;
/// ```
#[proc_macro]
pub fn device_from_eds(input: TokenStream) -> TokenStream {
    let eds_def = syn::parse_macro_input!(input as eds_parser::EdsDefinition);
    let track = eds_parser::track_source(&eds_def);
    let od = match eds_parser::parse_eds_to_od(eds_def) {
        Ok(od) => od,
        Err(error) => return error.to_compile_error().into(),
    };
    let generated: proc_macro2::TokenStream = generate_device(od).into();
    quote::quote! { #track #generated }.into()
}

/// Generate the high-level remote device API from EDS contents supplied by
/// another procedural macro.
///
/// This is the content counterpart of [`device_from_eds`]. It exists for EDS
/// provider crates that own and track a raw EDS file, then embed its contents
/// as the string literal in this otherwise identical declaration:
///
/// ```ignore
/// device_from_eds_content! {
///     pub struct Motor = "[FileInfo]\n...";
/// }
/// ```
#[proc_macro]
pub fn device_from_eds_content(input: TokenStream) -> TokenStream {
    let eds_def = syn::parse_macro_input!(input as eds_parser::EdsDefinition);
    let od = match eds_parser::parse_eds_content_to_od(eds_def) {
        Ok(od) => od,
        Err(error) => return error.to_compile_error().into(),
    };
    generate_device(od)
}

fn generate_device(od: dsl::OdDefinition) -> TokenStream {
    let sdo = sdo_client_codegen::generate_from_od(&od);
    let pdo = pdo_client_codegen::generate_for_device(&od);
    quote::quote! {
        #sdo
        #pdo
    }
    .into()
}
